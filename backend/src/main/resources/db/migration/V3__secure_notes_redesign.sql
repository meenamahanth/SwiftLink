-- Drop old secure_notes table (removes user_id, share_id, is_expired columns)
DROP TABLE IF EXISTS secure_notes;

-- Create new simplified secure_notes table
-- note_hash is the sole lookup key (SHA-256 of the user's secret code)
-- No user association. No share links. No is_expired flag.
-- Expiry is determined at query time by comparing expires_at with now().
CREATE TABLE secure_notes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_hash    VARCHAR(64)                  NOT NULL UNIQUE,
    encrypted_content TEXT                    NOT NULL,
    title        VARCHAR(255),
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE     NOT NULL
);

CREATE INDEX idx_secure_notes_note_hash  ON secure_notes(note_hash);
CREATE INDEX idx_secure_notes_expires_at ON secure_notes(expires_at);
