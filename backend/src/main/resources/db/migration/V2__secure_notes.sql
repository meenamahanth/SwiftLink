-- Ensure core URL shortener tables exist (handles databases baselined without running V1)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'ROLE_USER',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS short_urls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code VARCHAR(50) NOT NULL UNIQUE,
    long_url TEXT NOT NULL,
    custom_alias VARCHAR(50) UNIQUE,
    title VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    is_enabled BOOLEAN DEFAULT TRUE NOT NULL,
    click_count INTEGER DEFAULT 0 NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_short_urls_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS click_analytics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_url_id BIGINT NOT NULL,
    clicked_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    referrer VARCHAR(255),
    browser VARCHAR(100),
    operating_system VARCHAR(100),
    device_type VARCHAR(50),
    ip_address VARCHAR(45),
    CONSTRAINT fk_click_analytics_url FOREIGN KEY (short_url_id) REFERENCES short_urls(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_short_urls_user_id ON short_urls(user_id);
CREATE INDEX IF NOT EXISTS idx_short_urls_short_code ON short_urls(short_code);
CREATE INDEX IF NOT EXISTS idx_short_urls_custom_alias ON short_urls(custom_alias);
CREATE INDEX IF NOT EXISTS idx_click_analytics_url_id ON click_analytics(short_url_id);
CREATE INDEX IF NOT EXISTS idx_click_analytics_clicked_at ON click_analytics(clicked_at);

-- Create secure_notes table with expiration support
CREATE TABLE IF NOT EXISTS secure_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    note_hash VARCHAR(64) NOT NULL,
    encrypted_content TEXT NOT NULL,
    title VARCHAR(255),
    share_id VARCHAR(50) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    is_expired BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_secure_notes_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_secure_notes_user_id ON secure_notes(user_id);
CREATE INDEX IF NOT EXISTS idx_secure_notes_share_id ON secure_notes(share_id);
CREATE INDEX IF NOT EXISTS idx_secure_notes_note_hash ON secure_notes(note_hash);
CREATE INDEX IF NOT EXISTS idx_secure_notes_expires_at ON secure_notes(expires_at);
